-- V6: shelves. A product's stock can be spread over physical shelves
-- (e.g. A1: 2, A2: 3). Stock not on any shelf counts as "not on a shelf".
CREATE TABLE SHELF (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE         VARCHAR2(30)  NOT NULL,
    DESCRIPTION  VARCHAR2(200),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_SHELF_CODE UNIQUE (CODE)
);

-- How many units of a product are on a shelf.
CREATE TABLE SHELF_STOCK (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHELF_ID    NUMBER     NOT NULL,
    PRODUCT_ID  NUMBER     NOT NULL,
    QUANTITY    NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT UQ_SHELF_STOCK UNIQUE (SHELF_ID, PRODUCT_ID),
    CONSTRAINT FK_SS_SHELF FOREIGN KEY (SHELF_ID) REFERENCES SHELF (ID) ON DELETE CASCADE,
    CONSTRAINT FK_SS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID) ON DELETE CASCADE,
    CONSTRAINT CK_SS_QTY CHECK (QUANTITY >= 0)
);
CREATE INDEX IX_SS_PRODUCT ON SHELF_STOCK (PRODUCT_ID);

-- Which shelf a sale was taken from / a purchase was put on. The code is a
-- snapshot so old orders still show it if the shelf is renamed or deleted.
ALTER TABLE ORDER_LINE ADD (SHELF_ID NUMBER, SHELF_CODE VARCHAR2(30));
ALTER TABLE STOCK_ADJUSTMENT ADD (SHELF_ID NUMBER, SHELF_CODE VARCHAR2(30));
