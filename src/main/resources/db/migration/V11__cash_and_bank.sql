-- V11: Cash & Bank. Accounts (cash registers, bank accounts) and every money
-- movement in or out: payments and refunds (automatic), other income and
-- expenses, transfers between accounts and reconciliation corrections.

CREATE TABLE CASH_ACCOUNT (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME             VARCHAR2(100) NOT NULL,
    KIND             VARCHAR2(10)  NOT NULL,          -- CASH or BANK
    BANK_NAME        VARCHAR2(100),
    IBAN             VARCHAR2(50),
    OPENING_BALANCE  NUMBER(16,2)  DEFAULT 0 NOT NULL,
    OPENING_DATE     DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    ACTIVE           NUMBER(1)     DEFAULT 1 NOT NULL,
    IS_DEFAULT       NUMBER(1)     DEFAULT 0 NOT NULL, -- default account of its kind for payments
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CASH_ACCOUNT_NAME UNIQUE (NAME),
    CONSTRAINT CK_CASH_ACCOUNT_KIND CHECK (KIND IN ('CASH', 'BANK'))
);

CREATE TABLE MONEY_MOVEMENT (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID   NUMBER        NOT NULL,
    MOVED_ON     DATE          NOT NULL,
    DIRECTION    VARCHAR2(3)   NOT NULL,              -- IN or OUT
    AMOUNT       NUMBER(16,2)  NOT NULL,
    CATEGORY     VARCHAR2(30)  NOT NULL,
    DESCRIPTION  VARCHAR2(300),
    REF_NO       VARCHAR2(50),
    PAYMENT_ID   NUMBER,                              -- set when it comes from a payment or refund
    ORDER_TYPE   VARCHAR2(10),
    ORDER_CODE   VARCHAR2(20),
    TRANSFER_ID  NUMBER,                              -- the two halves of a transfer share this
    CREATED_BY   VARCHAR2(100) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_MOVE_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES CASH_ACCOUNT (ID),
    CONSTRAINT CK_MOVE_DIRECTION CHECK (DIRECTION IN ('IN', 'OUT')),
    CONSTRAINT CK_MOVE_AMOUNT CHECK (AMOUNT > 0)
);
CREATE INDEX IX_MOVE_ACCOUNT_DATE ON MONEY_MOVEMENT (ACCOUNT_ID, MOVED_ON);
CREATE INDEX IX_MOVE_PAYMENT ON MONEY_MOVEMENT (PAYMENT_ID);
CREATE INDEX IX_MOVE_ORDER ON MONEY_MOVEMENT (ORDER_TYPE, ORDER_CODE);

ALTER TABLE PAYMENT ADD (ACCOUNT_ID NUMBER);

-- Default accounts: "Arka" (cash) and "Banka" (bank), editable later.
INSERT INTO CASH_ACCOUNT (NAME, KIND, IS_DEFAULT) VALUES ('Arka', 'CASH', 1);
INSERT INTO CASH_ACCOUNT (NAME, KIND, IS_DEFAULT) VALUES ('Banka', 'BANK', 1);
-- They "open" on the date of the first payment, so past balances add up.
UPDATE CASH_ACCOUNT SET OPENING_DATE = LEAST(TRUNC(SYSDATE), NVL((SELECT MIN(PAID_ON) FROM PAYMENT), TRUNC(SYSDATE)));

-- Existing payments: cash payments to Arka, all others to Banka.
UPDATE PAYMENT SET ACCOUNT_ID = (SELECT ID FROM CASH_ACCOUNT WHERE NAME = 'Arka') WHERE PAY_METHOD = 'CASH';
UPDATE PAYMENT SET ACCOUNT_ID = (SELECT ID FROM CASH_ACCOUNT WHERE NAME = 'Banka') WHERE ACCOUNT_ID IS NULL;

-- ...and each becomes a movement.
INSERT INTO MONEY_MOVEMENT (ACCOUNT_ID, MOVED_ON, DIRECTION, AMOUNT, CATEGORY, DESCRIPTION, PAYMENT_ID,
                            ORDER_TYPE, ORDER_CODE, CREATED_BY, CREATED_AT)
SELECT p.ACCOUNT_ID, p.PAID_ON,
       CASE WHEN (p.ORDER_TYPE = 'SALE' AND p.PAY_KIND = 'PAYMENT') OR (p.ORDER_TYPE = 'PURCHASE' AND p.PAY_KIND = 'REFUND')
            THEN 'IN' ELSE 'OUT' END,
       p.AMOUNT,
       CASE WHEN p.ORDER_TYPE = 'SALE' AND p.PAY_KIND = 'PAYMENT' THEN 'SALE_PAYMENT'
            WHEN p.ORDER_TYPE = 'SALE' THEN 'SALE_REFUND'
            WHEN p.PAY_KIND = 'PAYMENT' THEN 'PURCHASE_PAYMENT'
            ELSE 'PURCHASE_REFUND' END,
       p.NOTE, p.ID, p.ORDER_TYPE, p.ORDER_CODE, p.CREATED_BY, p.CREATED_AT
FROM PAYMENT p;
