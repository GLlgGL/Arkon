-- V12: optional modules (all off by default) and cost centres.

ALTER TABLE APP_CONFIG ADD (
    MOD_CASH          NUMBER(1) DEFAULT 0 NOT NULL,   -- Cash & Bank
    MOD_COST_CENTERS  NUMBER(1) DEFAULT 0 NOT NULL    -- Cost centres
);

-- Cost centres ("qendra e kostos"): a project, branch, department or product
-- line that revenue, costs and expenses are grouped by.
CREATE TABLE COST_CENTER (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE         VARCHAR2(20)  NOT NULL,
    NAME         VARCHAR2(100) NOT NULL,
    DESCRIPTION  VARCHAR2(300),
    ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_COST_CENTER_CODE UNIQUE (CODE)
);

-- Sales and purchases are assigned per order; other income and expenses per movement.
ALTER TABLE ORDER_INFO ADD (COST_CENTER_ID NUMBER);
ALTER TABLE MONEY_MOVEMENT ADD (COST_CENTER_ID NUMBER);
