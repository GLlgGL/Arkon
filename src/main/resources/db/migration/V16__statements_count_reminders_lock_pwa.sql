-- V16: client/supplier statements, stock count, notifications and payment
-- reminders, period lock and year-end closing, installable app. All optional, off.

ALTER TABLE APP_CONFIG ADD (
    MOD_STATEMENTS   NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_STOCK_COUNT  NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_REMINDERS    NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_PERIOD_LOCK  NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_PWA          NUMBER(1) DEFAULT 0 NOT NULL,
    LOCK_DATE        DATE,                                -- nothing on or before this date can change
    REM_DAYS_BEFORE  NUMBER(3) DEFAULT 3 NOT NULL,        -- remind this many days before the due date
    REM_DAYS_AFTER   NUMBER(3) DEFAULT 7 NOT NULL,        -- then every this many days while overdue
    REM_AUTO         NUMBER(1) DEFAULT 0 NOT NULL         -- send automatically every morning
);

CREATE SEQUENCE STOCK_COUNT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE STOCK_COUNT (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE        VARCHAR2(20)  NOT NULL,
    COUNTED_ON  DATE          NOT NULL,
    STATUS      VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,     -- OPEN, APPLIED, CANCELLED
    NOTE        VARCHAR2(300),
    CREATED_BY  VARCHAR2(100) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    APPLIED_AT  TIMESTAMP,
    CONSTRAINT UQ_STOCK_COUNT_CODE UNIQUE (CODE)
);
CREATE TABLE STOCK_COUNT_LINE (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COUNT_ID      NUMBER NOT NULL,
    PRODUCT_NAME  VARCHAR2(200) NOT NULL,
    UNIT          VARCHAR2(30),
    EXPECTED      NUMBER(12) NOT NULL,
    COUNTED       NUMBER(12),
    CONSTRAINT FK_SCL_COUNT FOREIGN KEY (COUNT_ID) REFERENCES STOCK_COUNT (ID) ON DELETE CASCADE
);

CREATE TABLE REMINDER_LOG (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_CODE  VARCHAR2(20)  NOT NULL,
    KIND        VARCHAR2(10)  NOT NULL,                    -- BEFORE or AFTER the due date
    SENT_TO     VARCHAR2(200) NOT NULL,
    SENT_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_REMINDER_ORDER ON REMINDER_LOG (ORDER_CODE);
