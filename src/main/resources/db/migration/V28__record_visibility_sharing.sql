-- V28: which records each user sees, and sharing records with other users.
-- RECORD_SCOPE: ALL = everyone's records, OWN = own records + shared with them, empty = as the role
-- (administrators and accountants see all, users their own — as before).
ALTER TABLE APP_USER ADD (RECORD_SCOPE VARCHAR2(4));

-- A user shares records with another user, view only: all their records (ORDER_CODE empty) or one record.
CREATE TABLE RECORD_SHARE (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER       VARCHAR2(100) NOT NULL,
    GRANTEE     VARCHAR2(100) NOT NULL,
    ORDER_TYPE  VARCHAR2(10),
    ORDER_CODE  VARCHAR2(20),
    NOTE        VARCHAR2(200),
    CREATED_BY  VARCHAR2(100) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_RECORD_SHARE_GRANTEE ON RECORD_SHARE (GRANTEE);
CREATE INDEX IX_RECORD_SHARE_OWNER ON RECORD_SHARE (OWNER);
