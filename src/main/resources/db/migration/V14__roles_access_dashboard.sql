-- V14: Accountant role, per-user access to each area, personal dashboards.

ALTER TABLE APP_USER DROP CONSTRAINT CK_APP_USER_ROLE;
ALTER TABLE APP_USER ADD CONSTRAINT CK_APP_USER_ROLE CHECK (USER_ROLE IN (1, 2, 3));   -- 1 admin, 2 user, 3 accountant

-- Overrides of the role's default access: NONE, VIEW or FULL per area.
CREATE TABLE USER_ACCESS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME      VARCHAR2(100) NOT NULL,
    AREA          VARCHAR2(30)  NOT NULL,
    ACCESS_LEVEL  VARCHAR2(5)   NOT NULL,
    CONSTRAINT UQ_USER_ACCESS UNIQUE (USERNAME, AREA),
    CONSTRAINT CK_USER_ACCESS CHECK (ACCESS_LEVEL IN ('NONE', 'VIEW', 'FULL'))
);

-- Each user's dashboard: the chosen widgets in order.
CREATE TABLE USER_DASHBOARD (
    USERNAME  VARCHAR2(100) PRIMARY KEY,
    WIDGETS   VARCHAR2(1000) NOT NULL
);
