-- V9: returns on sales (credit notes), refunds, invoice language, purchase orders.

-- Returns are minus lines on the sale they belong to, so every total
-- (stock, reports, statistics, debts) goes down automatically.
ALTER TABLE ORDER_LINE DROP CONSTRAINT CK_ORDER_LINE_QTY;
ALTER TABLE ORDER_LINE ADD CONSTRAINT CK_ORDER_LINE_QTY CHECK (QUANTITY <> 0);
ALTER TABLE ORDER_LINE ADD (
    RETURN_OF  NUMBER,        -- the sale line that was returned
    RETURN_NO  NUMBER(5)      -- credit note number within the sale (1, 2, ...)
);

-- Refunds paid back to a client are recorded as payments of kind REFUND.
ALTER TABLE PAYMENT ADD (PAY_KIND VARCHAR2(10) DEFAULT 'PAYMENT' NOT NULL);
ALTER TABLE PAYMENT ADD CONSTRAINT CK_PAYMENT_KIND CHECK (PAY_KIND IN ('PAYMENT', 'REFUND'));

-- Language of invoice PDFs, credit notes, purchase orders and pick lists.
ALTER TABLE APP_CONFIG ADD (INVOICE_LANG VARCHAR2(5) DEFAULT 'en' NOT NULL);

-- Purchase orders: a request to a merchant. No effect on stock until received.
CREATE SEQUENCE PO_CODE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PURCHASE_ORDER (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE           VARCHAR2(20)  NOT NULL,
    MERCHANT_NAME  VARCHAR2(200) NOT NULL,
    COMPANY_NAME   VARCHAR2(200) NOT NULL,
    STATUS         VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,
    NOTE           VARCHAR2(500),
    PURCHASE_CODE  VARCHAR2(20),
    CREATED_BY     VARCHAR2(100) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_PO_CODE UNIQUE (CODE),
    CONSTRAINT CK_PO_STATUS CHECK (STATUS IN ('OPEN', 'RECEIVED', 'CANCELLED'))
);
CREATE TABLE PURCHASE_ORDER_LINE (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PO_ID         NUMBER        NOT NULL,
    PRODUCT_NAME  VARCHAR2(200) NOT NULL,
    UNIT          VARCHAR2(30),
    QUANTITY      NUMBER(10)    NOT NULL,
    UNIT_PRICE    NUMBER(14,2)  NOT NULL,
    CONSTRAINT FK_POL_PO FOREIGN KEY (PO_ID) REFERENCES PURCHASE_ORDER (ID) ON DELETE CASCADE,
    CONSTRAINT CK_POL_QTY CHECK (QUANTITY > 0)
);
