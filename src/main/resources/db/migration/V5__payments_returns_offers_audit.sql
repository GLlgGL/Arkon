-- V5: payments and debts, offer status and conversion, stock adjustments
-- (returns, damage, stock counts), real purchase cost, product barcodes,
-- audit log, and the related settings.

-- Barcode / product code (optional, unique when set)
ALTER TABLE PRODUCT ADD (CODE VARCHAR2(50));
ALTER TABLE PRODUCT ADD CONSTRAINT UQ_PRODUCT_CODE UNIQUE (CODE);

-- Cost of the goods on a sale line: the average purchase cost when it was sold.
-- Older lines stay NULL and fall back to the product's buy price in statistics.
ALTER TABLE ORDER_LINE ADD (UNIT_COST NUMBER(14,2));

-- One row per order with the information that isn't per line.
CREATE TABLE ORDER_INFO (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_TYPE    VARCHAR2(10)  NOT NULL,
    ORDER_CODE    VARCHAR2(20)  NOT NULL,
    DUE_DATE      DATE,                      -- sales and purchases: when payment is due
    OFFER_STATUS  VARCHAR2(10),              -- offers: OPEN, ACCEPTED, REJECTED
    VALID_UNTIL   DATE,                      -- offers
    CONVERTED_TO  VARCHAR2(20),              -- offers: the sale number it became
    CONSTRAINT UQ_ORDER_INFO UNIQUE (ORDER_TYPE, ORDER_CODE),
    CONSTRAINT CK_ORDER_INFO_STATUS CHECK (OFFER_STATUS IN ('OPEN', 'ACCEPTED', 'REJECTED'))
);

-- Money received from clients (SALE) or paid to merchants (PURCHASE).
CREATE TABLE PAYMENT (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_TYPE  VARCHAR2(10)  NOT NULL,
    ORDER_CODE  VARCHAR2(20)  NOT NULL,
    PAID_ON     DATE          NOT NULL,
    AMOUNT      NUMBER(16,2)  NOT NULL,
    PAY_METHOD  VARCHAR2(20)  NOT NULL,
    NOTE        VARCHAR2(300),
    CREATED_BY  VARCHAR2(100) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_PAYMENT_TYPE CHECK (ORDER_TYPE IN ('SALE', 'PURCHASE')),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0)
);
CREATE INDEX IX_PAYMENT_ORDER ON PAYMENT (ORDER_TYPE, ORDER_CODE);

-- Stock changes that aren't purchases or sales: returns, damage, losses, stock counts.
-- QUANTITY is signed: positive adds to stock, negative removes.
CREATE TABLE STOCK_ADJUSTMENT (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME  VARCHAR2(200) NOT NULL,
    QUANTITY      NUMBER(10)    NOT NULL,
    REASON        VARCHAR2(30)  NOT NULL,
    REF_NO        VARCHAR2(50),
    NOTE          VARCHAR2(300),
    CREATED_BY    VARCHAR2(100) NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_ADJ_QTY CHECK (QUANTITY <> 0)
);
CREATE INDEX IX_ADJ_PRODUCT ON STOCK_ADJUSTMENT (PRODUCT_NAME);
CREATE INDEX IX_ADJ_DATE ON STOCK_ADJUSTMENT (CREATED_AT);

-- Who did what and when.
CREATE TABLE AUDIT_LOG (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGGED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    USERNAME     VARCHAR2(100) NOT NULL,
    ACTION_NAME  VARCHAR2(40)  NOT NULL,
    ENTITY       VARCHAR2(40)  NOT NULL,
    ENTITY_KEY   VARCHAR2(200),
    DETAILS      VARCHAR2(1000)
);
CREATE INDEX IX_AUDIT_AT ON AUDIT_LOG (LOGGED_AT);

-- Settings: default payment terms and offer validity.
ALTER TABLE APP_CONFIG ADD (
    PAYMENT_TERMS_DAYS  NUMBER(4) DEFAULT 30 NOT NULL,
    OFFER_VALID_DAYS    NUMBER(4) DEFAULT 15 NOT NULL
);
