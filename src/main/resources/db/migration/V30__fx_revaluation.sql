-- V30: year-end exchange rate adjustment (revaluation of EUR / USD balances and open invoices).

-- Year-end exchange rate adjustment: each revaluation run and its items (to undo it, and to avoid running a date twice)
CREATE TABLE FX_REVAL (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REVAL_DATE  DATE          NOT NULL,
    ITEM_KEY    VARCHAR2(60)  NOT NULL,
    LABEL       VARCHAR2(200),
    CURRENCY    VARCHAR2(3)   NOT NULL,
    FX_AMOUNT   NUMBER(16,2)  NOT NULL,
    RATE        NUMBER(14,6)  NOT NULL,
    BOOK        NUMBER(16,2)  NOT NULL,
    DIFF        NUMBER(16,2)  NOT NULL,
    ENTRY_ID    NUMBER,
    REVERSAL_ID NUMBER
);
CREATE INDEX IX_FX_REVAL_DATE ON FX_REVAL (REVAL_DATE);
