-- V8: email settings, edited under Administration -> Email settings.
-- MAIL_SECURITY: STARTTLS (usually port 587), SSL (usually 465) or NONE.
ALTER TABLE APP_CONFIG ADD (
    MAIL_ENABLED   NUMBER(1)     DEFAULT 0 NOT NULL,
    MAIL_HOST      VARCHAR2(200),
    MAIL_PORT      NUMBER(5)     DEFAULT 587 NOT NULL,
    MAIL_SECURITY  VARCHAR2(10)  DEFAULT 'STARTTLS' NOT NULL,
    MAIL_USERNAME  VARCHAR2(200),
    MAIL_PASSWORD  VARCHAR2(500),
    MAIL_FROM      VARCHAR2(200),
    CONSTRAINT CK_MAIL_SECURITY CHECK (MAIL_SECURITY IN ('STARTTLS', 'SSL', 'NONE'))
);
