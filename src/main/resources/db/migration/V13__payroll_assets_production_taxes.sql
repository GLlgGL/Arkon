CREATE TABLE EMPLOYEE (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(150) NOT NULL,
    PERSONAL_NO    VARCHAR2(30),
    POSITION       VARCHAR2(100),
    GROSS_SALARY   NUMBER(14,2) NOT NULL,
    START_DATE     DATE NOT NULL,
    END_DATE       DATE,
    IBAN           VARCHAR2(50),
    COST_CENTER_ID NUMBER,
    ACTIVE         NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE PAYROLL_RUN (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERIOD      VARCHAR2(7) NOT NULL,                       -- YYYY-MM
    STATUS      VARCHAR2(10) DEFAULT 'DRAFT' NOT NULL,      -- DRAFT, APPROVED, PAID
    PAID_ON     DATE,
    CREATED_BY  VARCHAR2(100) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_PAYROLL_PERIOD UNIQUE (PERIOD),
    CONSTRAINT CK_PAYROLL_STATUS CHECK (STATUS IN ('DRAFT', 'APPROVED', 'PAID'))
);
CREATE TABLE PAYROLL_LINE (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID         NUMBER NOT NULL,
    EMPLOYEE_ID    NUMBER,
    EMPLOYEE_NAME  VARCHAR2(150) NOT NULL,
    GROSS          NUMBER(14,2) NOT NULL,
    EMP_SOCIAL     NUMBER(14,2) NOT NULL,
    EMP_HEALTH     NUMBER(14,2) NOT NULL,
    TAX            NUMBER(14,2) NOT NULL,
    NET            NUMBER(14,2) NOT NULL,
    ER_SOCIAL      NUMBER(14,2) NOT NULL,
    ER_HEALTH      NUMBER(14,2) NOT NULL,
    TOTAL_COST     NUMBER(14,2) NOT NULL,
    COST_CENTER_ID NUMBER,
    CONSTRAINT FK_PAYLINE_RUN FOREIGN KEY (RUN_ID) REFERENCES PAYROLL_RUN (ID) ON DELETE CASCADE
);

CREATE TABLE ASSET (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE           VARCHAR2(30)  NOT NULL,
    NAME           VARCHAR2(150) NOT NULL,
    CATEGORY       VARCHAR2(60),
    LOCATION       VARCHAR2(100),
    PURCHASE_DATE  DATE NOT NULL,
    COST           NUMBER(16,2) NOT NULL,
    SALVAGE        NUMBER(16,2) DEFAULT 0 NOT NULL,
    LIFE_MONTHS    NUMBER(5) NOT NULL,
    METHOD         VARCHAR2(12) DEFAULT 'STRAIGHT' NOT NULL,   -- STRAIGHT or DECLINING
    RATE           NUMBER(6,3),                               -- declining: % per year
    COST_CENTER_ID NUMBER,
    STATUS         VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,    -- ACTIVE or DISPOSED
    DISPOSAL_DATE  DATE,
    DISPOSAL_VALUE NUMBER(16,2),
    NOTE           VARCHAR2(300),
    CONSTRAINT UQ_ASSET_CODE UNIQUE (CODE)
);

-- Bill of materials: a finished product made from components.
CREATE TABLE BOM_LINE (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID    NUMBER NOT NULL,
    COMPONENT_ID  NUMBER NOT NULL,
    QUANTITY      NUMBER(10) NOT NULL,
    CONSTRAINT FK_BOM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID) ON DELETE CASCADE,
    CONSTRAINT FK_BOM_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES PRODUCT (ID) ON DELETE CASCADE,
    CONSTRAINT CK_BOM_QTY CHECK (QUANTITY > 0)
);
CREATE SEQUENCE PRODUCTION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PRODUCTION_ORDER (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE          VARCHAR2(20)  NOT NULL,
    PRODUCT_NAME  VARCHAR2(200) NOT NULL,
    QUANTITY      NUMBER(10)    NOT NULL,
    STATUS        VARCHAR2(10)  DEFAULT 'DRAFT' NOT NULL,   -- DRAFT, DONE, CANCELLED
    PLANNED_ON    DATE,
    DONE_AT       TIMESTAMP,
    UNIT_COST     NUMBER(14,2),
    TOTAL_COST    NUMBER(16,2),
    NOTE          VARCHAR2(300),
    CREATED_BY    VARCHAR2(100) NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_PRODUCTION_CODE UNIQUE (CODE),
    CONSTRAINT CK_PRODUCTION_QTY CHECK (QUANTITY > 0)
);
CREATE TABLE PRODUCTION_LINE (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID        NUMBER NOT NULL,
    COMPONENT_NAME  VARCHAR2(200) NOT NULL,
    UNIT            VARCHAR2(30),
    QUANTITY        NUMBER(10) NOT NULL,
    UNIT_COST       NUMBER(14,2),
    CONSTRAINT FK_PRODLINE_ORDER FOREIGN KEY (ORDER_ID) REFERENCES PRODUCTION_ORDER (ID) ON DELETE CASCADE
);

-- Taxes paid (VAT and payroll taxes), per month.
CREATE TABLE TAX_PAYMENT (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    KIND        VARCHAR2(10) NOT NULL,       -- VAT or PAYROLL
    PERIOD      VARCHAR2(7)  NOT NULL,       -- YYYY-MM the tax belongs to
    AMOUNT      NUMBER(16,2) NOT NULL,
    PAID_ON     DATE NOT NULL,
    NOTE        VARCHAR2(300),
    CREATED_BY  VARCHAR2(100) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_TAX_KIND CHECK (KIND IN ('VAT', 'PAYROLL'))
);
