    MOD_ASSETS      NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_PRODUCTION  NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_TAXES       NUMBER(1) DEFAULT 0 NOT NULL,
    -- Payroll rates (Albania 2026 defaults; editable, check with your accountant)
    PR_EMP_SOCIAL   NUMBER(6,3) DEFAULT 9.5  NOT NULL,
    PR_EMP_HEALTH   NUMBER(6,3) DEFAULT 1.7  NOT NULL,
    PR_ER_SOCIAL    NUMBER(6,3) DEFAULT 15   NOT NULL,
    PR_ER_HEALTH    NUMBER(6,3) DEFAULT 1.7  NOT NULL,
    PR_MIN_BASE     NUMBER(14,2) DEFAULT 50000  NOT NULL,   -- minimum wage
    PR_MAX_BASE     NUMBER(14,2) DEFAULT 186416 NOT NULL,   -- contribution ceiling
    PR_TAX_ON_NET   NUMBER(1) DEFAULT 0 NOT NULL,           -- 1 = income tax after employee contributions
    TAX_VAT_DAY     NUMBER(2) DEFAULT 14 NOT NULL,          -- VAT due on this day of the next month
    TAX_PAYROLL_DAY NUMBER(2) DEFAULT 20 NOT NULL           -- payroll taxes due on this day of the next month
);

-- Monthly income tax (TAP): tax = FIXED + RATE% x (gross - OVER) for gross between FROM and TO.
CREATE TABLE PAYROLL_TAX_BRACKET (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FROM_AMOUNT  NUMBER(14,2) NOT NULL,
    TO_AMOUNT    NUMBER(14,2),
    FIXED_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    RATE         NUMBER(6,3)  DEFAULT 0 NOT NULL,
    OVER_AMOUNT  NUMBER(14,2) DEFAULT 0 NOT NULL
);
