-- V18: multi-currency (EUR, USD) next to the base currency (ALL). Optional, off.
-- Every amount stays stored in the base currency too, so all reports keep working.

ALTER TABLE APP_CONFIG ADD (MOD_CURRENCIES NUMBER(1) DEFAULT 0 NOT NULL);

-- Daily rates: 1 unit of CURRENCY = RATE units of the base currency
CREATE TABLE EXCHANGE_RATE (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RATE_DATE  DATE         NOT NULL,
    CURRENCY   VARCHAR2(3)  NOT NULL,
    RATE       NUMBER(14,6) NOT NULL,
    CONSTRAINT UQ_EXCHANGE_RATE UNIQUE (RATE_DATE, CURRENCY),
    CONSTRAINT CK_EXCHANGE_RATE CHECK (RATE > 0)
);

-- An order's currency and its rate (null = base currency)
ALTER TABLE ORDER_INFO ADD (CURRENCY VARCHAR2(3), FX_RATE NUMBER(14,6));
-- A payment as entered, in the order's currency
ALTER TABLE PAYMENT ADD (FX_CURRENCY VARCHAR2(3), FX_AMOUNT NUMBER(16,2));
-- Cash registers and bank accounts in a foreign currency
ALTER TABLE CASH_ACCOUNT ADD (CURRENCY VARCHAR2(3));
ALTER TABLE MONEY_MOVEMENT ADD (FX_AMOUNT NUMBER(16,2));     -- amount in the account's currency
