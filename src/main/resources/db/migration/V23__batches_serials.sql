-- V23: batch / expiry and serial number tracking per product. Optional module (off by default).

ALTER TABLE APP_CONFIG ADD (MOD_TRACKING NUMBER(1) DEFAULT 0 NOT NULL);
ALTER TABLE PRODUCT ADD (TRACKING VARCHAR2(10) DEFAULT 'NONE' NOT NULL);       -- NONE, BATCH, SERIAL

ALTER TABLE ORDER_LINE ADD (BATCH_NO VARCHAR2(60), EXPIRY_DATE DATE);
ALTER TABLE STOCK_ADJUSTMENT ADD (BATCH_NO VARCHAR2(60), EXPIRY_DATE DATE);
CREATE INDEX IX_LINE_BATCH ON ORDER_LINE (PRODUCT_NAME, BATCH_NO);

-- One row per unit of a serial-tracked product.
CREATE TABLE SERIAL_NUMBER (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME      VARCHAR2(200) NOT NULL,
    SERIAL            VARCHAR2(100) NOT NULL,
    STATUS            VARCHAR2(10)  DEFAULT 'IN_STOCK' NOT NULL,   -- IN_STOCK, SOLD, RETURNED (to supplier), REMOVED
    LOCATION_ID       NUMBER,
    PURCHASE_LINE_ID  NUMBER,
    PURCHASE_CODE     VARCHAR2(20),
    PURCHASED_ON      DATE,
    SALE_LINE_ID      NUMBER,
    SALE_CODE         VARCHAR2(20),
    SOLD_ON           DATE,
    CONSTRAINT UQ_SERIAL UNIQUE (PRODUCT_NAME, SERIAL)
);
CREATE INDEX IX_SERIAL_SEARCH ON SERIAL_NUMBER (SERIAL);
