-- V15: Accounting (kontabilitet), optional module (off by default).

ALTER TABLE APP_CONFIG ADD (MOD_ACCOUNTING NUMBER(1) DEFAULT 0 NOT NULL);

-- Where a Cash & Bank movement came from when a module made it (PAYROLL, TAX),
-- so accounting doesn't count it twice.
ALTER TABLE MONEY_MOVEMENT ADD (ORIGIN VARCHAR2(10));

-- Chart of accounts. SYSTEM_KEY marks accounts the automatic entries use.
CREATE TABLE ACC_ACCOUNT (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE        VARCHAR2(20)  NOT NULL,
    NAME        VARCHAR2(150) NOT NULL,
    TYPE        VARCHAR2(10)  NOT NULL,     -- ASSET, LIABILITY, EQUITY, INCOME, EXPENSE
    SYSTEM_KEY  VARCHAR2(30),
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_ACC_CODE UNIQUE (CODE),
    CONSTRAINT UQ_ACC_SYSKEY UNIQUE (SYSTEM_KEY),
    CONSTRAINT CK_ACC_TYPE CHECK (TYPE IN ('ASSET', 'LIABILITY', 'EQUITY', 'INCOME', 'EXPENSE'))
);

CREATE SEQUENCE ACC_ENTRY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ACC_ENTRY (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTRY_NO     VARCHAR2(20)  NOT NULL,
    ENTRY_DATE   DATE          NOT NULL,
    DESCRIPTION  VARCHAR2(300) NOT NULL,
    SOURCE       VARCHAR2(15)  NOT NULL,    -- MANUAL or the automatic source
    SOURCE_REF   VARCHAR2(60),
    CREATED_BY   VARCHAR2(100) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ACC_ENTRY_NO UNIQUE (ENTRY_NO)
);
CREATE INDEX IX_ACC_ENTRY_DATE ON ACC_ENTRY (ENTRY_DATE);

CREATE TABLE ACC_LINE (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTRY_ID    NUMBER NOT NULL,
    ACCOUNT_ID  NUMBER NOT NULL,
    DEBIT       NUMBER(16,2) DEFAULT 0 NOT NULL,
    CREDIT      NUMBER(16,2) DEFAULT 0 NOT NULL,
    NOTE        VARCHAR2(200),
    CONSTRAINT FK_ACCLINE_ENTRY FOREIGN KEY (ENTRY_ID) REFERENCES ACC_ENTRY (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ACCLINE_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACC_ACCOUNT (ID)
);
CREATE INDEX IX_ACC_LINE_ACCOUNT ON ACC_LINE (ACCOUNT_ID);

