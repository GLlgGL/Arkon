-- =====================================================================
-- Oracle schema for the Financial Management System.
--
-- Reconstructed from the SQL Server queries in the ASP.NET code-behind.
-- Original -> new table names:
--   Users          -> APP_USER        (USER is reserved in Oracle)
--   Merchants      -> MERCHANT        (suppliers you buy from)
--   Companies      -> COMPANY         (your own company / companies)
--   Clients        -> CLIENT          (customers you sell to)
--   NotClients     -> PROSPECT        (offer recipients not yet clients)
--   Products       -> PRODUCT
--   PClasses       -> PRODUCT_CLASS   (+ PRODUCT.PRODUCT_CLASS_ID)
--   CClass         -> CLIENT_CLASS_DISCOUNT (rows instead of one column per class)
--   Configurations -> APP_CONFIG
--   Purchases, Sales, Offers -> ORDER_LINE with ORDER_TYPE
--
-- Money columns are NUMBER instead of the comma-formatted strings the
-- original stored (which forced REPLACE(ValuewithVAT, ',', '') in reports).
-- Requires Oracle 12c or later (identity columns).
-- =====================================================================

CREATE TABLE APP_USER (
    ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME               VARCHAR2(100)  NOT NULL,
    LAST_NAME                VARCHAR2(100)  NOT NULL,
    EMAIL                    VARCHAR2(200),
    USERNAME                 VARCHAR2(100)  NOT NULL,
    PASSWORD                 VARCHAR2(200)  NOT NULL,
    USER_ROLE                NUMBER(1)      DEFAULT 2 NOT NULL,
    LAST_LOGIN_AT            TIMESTAMP,
    LAST_PASSWORD_CHANGE_AT  TIMESTAMP,
    CONSTRAINT UQ_APP_USER_USERNAME UNIQUE (USERNAME),
    -- 1 = Administrator, 2 = User (same codes as the original UserRole column)
    CONSTRAINT CK_APP_USER_ROLE CHECK (USER_ROLE IN (1, 2))
);

CREATE TABLE MERCHANT (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(200) NOT NULL,
    TIN            VARCHAR2(50),
    ADDRESS        VARCHAR2(300),
    EMAIL          VARCHAR2(200),
    PHONE          VARCHAR2(50),
    REGISTERED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_MERCHANT_NAME UNIQUE (NAME)
);

CREATE TABLE COMPANY (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(200) NOT NULL,
    TIN            VARCHAR2(50),
    ADDRESS        VARCHAR2(300),
    EMAIL          VARCHAR2(200),
    PHONE          VARCHAR2(50),
    REGISTERED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_COMPANY_NAME UNIQUE (NAME)
);

CREATE TABLE CLIENT (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(200) NOT NULL,
    TIN            VARCHAR2(50),
    ADDRESS        VARCHAR2(300),
    EMAIL          VARCHAR2(200),
    PHONE          VARCHAR2(50),
    REGISTERED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CLIENT_NAME UNIQUE (NAME)
);

-- Recipients of offers who are not registered clients (was NotClients).
-- Not unique: the original inserted a row every time an offer line was added.
CREATE TABLE PROSPECT (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(200) NOT NULL,
    TIN            VARCHAR2(50),
    ADDRESS        VARCHAR2(300),
    EMAIL          VARCHAR2(200),
    PHONE          VARCHAR2(50),
    REGISTERED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_PROSPECT_NAME ON PROSPECT (NAME);

CREATE TABLE PRODUCT_CLASS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME           VARCHAR2(100) NOT NULL,
    REGISTERED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_PRODUCT_CLASS_NAME UNIQUE (NAME)
);

CREATE TABLE PRODUCT (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME              VARCHAR2(200) NOT NULL,
    UNIT              VARCHAR2(30)  NOT NULL,
    BUY_PRICE         NUMBER(14,2)  DEFAULT 0 NOT NULL,
    SALE_PRICE        NUMBER(14,2)  DEFAULT 0 NOT NULL,
    -- Original "productquantitylimit": a sale above this shows a warning.
    QUANTITY_LIMIT    NUMBER(10)    DEFAULT 0 NOT NULL,
    PRODUCT_CLASS_ID  NUMBER,
    REGISTERED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_PRODUCT_NAME UNIQUE (NAME),
    CONSTRAINT FK_PRODUCT_CLASS FOREIGN KEY (PRODUCT_CLASS_ID)
        REFERENCES PRODUCT_CLASS (ID) ON DELETE SET NULL
);

-- Replaces CClass, where every product class was an extra column added at
-- runtime with ALTER TABLE. One row = one client's discount for one class.
CREATE TABLE CLIENT_CLASS_DISCOUNT (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID         NUMBER       NOT NULL,
    PRODUCT_CLASS_ID  NUMBER       NOT NULL,
    DISCOUNT_PERCENT  NUMBER(5,2)  DEFAULT 0 NOT NULL,
    REGISTERED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CCD UNIQUE (CLIENT_ID, PRODUCT_CLASS_ID),
    CONSTRAINT FK_CCD_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENT (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CCD_CLASS FOREIGN KEY (PRODUCT_CLASS_ID)
        REFERENCES PRODUCT_CLASS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_CCD_PERCENT CHECK (DISCOUNT_PERCENT BETWEEN 0 AND 100)
);

-- Single-row settings table (was Configurations, always read as Id = 1).
-- VAT_PERCENT was the confusingly named "TIN" column; the app divided it by 100.
CREATE TABLE APP_CONFIG (
    ID           NUMBER(1)     DEFAULT 1 PRIMARY KEY,
    CURRENCY     VARCHAR2(10)  DEFAULT 'ALL' NOT NULL,
    VAT_PERCENT  NUMBER(5,2)   DEFAULT 20 NOT NULL,
    -- Invoice accent colour, stored as "R,G,B" like the original RGB column.
    BRAND_RGB    VARCHAR2(20)  DEFAULT '11,71,121' NOT NULL,
    LOGO_FILE    VARCHAR2(200),
    CONSTRAINT CK_APP_CONFIG_SINGLE CHECK (ID = 1)
);

-- Purchases, Sales and Offers had identical columns, so they share one table.
-- Each row is one line of an order; lines with the same ORDER_TYPE +
-- ORDER_CODE form one order. Names are stored as text snapshots, as in the
-- original, so old invoices stay correct if a client or product is renamed.
CREATE TABLE ORDER_LINE (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_TYPE        VARCHAR2(10)   NOT NULL,
    ORDER_CODE        VARCHAR2(20)   NOT NULL,
    CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    PRODUCT_NAME      VARCHAR2(200)  NOT NULL,
    PROVIDER_NAME     VARCHAR2(200)  NOT NULL,
    BUYER_NAME        VARCHAR2(200)  NOT NULL,
    UNIT              VARCHAR2(30),
    QUANTITY          NUMBER(10)     NOT NULL,
    UNIT_PRICE        NUMBER(14,2)   NOT NULL,
    DISCOUNT_PERCENT  NUMBER(5,2)    DEFAULT 0 NOT NULL,
    VALUE_NO_VAT      NUMBER(16,2)   NOT NULL,
    VAT_VALUE         NUMBER(16,2)   NOT NULL,
    VALUE_WITH_VAT    NUMBER(16,2)   NOT NULL,
    CREATED_BY        VARCHAR2(100)  NOT NULL,
    -- Offers only: 'Y' if the buyer is a registered client (was 'YES'/'NO').
    EXISTING_CLIENT   CHAR(1),
    LAST_UPDATED      TIMESTAMP,
    CONSTRAINT CK_ORDER_LINE_TYPE CHECK (ORDER_TYPE IN ('PURCHASE', 'SALE', 'OFFER')),
    CONSTRAINT CK_ORDER_LINE_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CK_ORDER_LINE_EXISTING CHECK (EXISTING_CLIENT IN ('Y', 'N'))
);
CREATE INDEX IX_ORDER_LINE_CODE    ON ORDER_LINE (ORDER_TYPE, ORDER_CODE);
CREATE INDEX IX_ORDER_LINE_DATE    ON ORDER_LINE (ORDER_TYPE, CREATED_AT);
CREATE INDEX IX_ORDER_LINE_PRODUCT ON ORDER_LINE (ORDER_TYPE, PRODUCT_NAME);
CREATE INDEX IX_ORDER_LINE_USER    ON ORDER_LINE (CREATED_BY);

-- Order numbers. The original picked 8 random digits, which could collide.
-- After importing old data, restart this above the highest imported code
-- (see migration/README-data-migration.md).
CREATE SEQUENCE ORDER_CODE_SEQ START WITH 10000000 INCREMENT BY 1 NOCACHE;
