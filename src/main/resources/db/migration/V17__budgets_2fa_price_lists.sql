-- V17: budgets and cash-flow forecast, two-step login, price lists. All optional, off.

ALTER TABLE APP_CONFIG ADD (
    MOD_BUDGETS      NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_2FA          NUMBER(1) DEFAULT 0 NOT NULL,
    MOD_PRICE_LISTS  NUMBER(1) DEFAULT 0 NOT NULL,
    TFA_REQUIRED     NUMBER(1) DEFAULT 0 NOT NULL      -- everyone must set up two-step login
);

-- Two-step login (TOTP authenticator apps)
ALTER TABLE APP_USER ADD (
    TOTP_SECRET   VARCHAR2(64),
    TOTP_ENABLED  NUMBER(1) DEFAULT 0 NOT NULL
);

-- Budget: one amount per year, line and month
CREATE TABLE BUDGET_LINE (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUDGET_YEAR  NUMBER(4)    NOT NULL,
    LINE_KEY     VARCHAR2(30) NOT NULL,     -- SALES, COGS, OTHER_INCOME or an expense category
    MONTH_NO     NUMBER(2)    NOT NULL,
    AMOUNT       NUMBER(16,2) DEFAULT 0 NOT NULL,
    CONSTRAINT UQ_BUDGET_LINE UNIQUE (BUDGET_YEAR, LINE_KEY, MONTH_NO)
);

-- Price lists: a price per product; clients can be given a list
CREATE TABLE PRICE_LIST (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME         VARCHAR2(100) NOT NULL,
    DESCRIPTION  VARCHAR2(300),
    ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_PRICE_LIST_NAME UNIQUE (NAME)
);
CREATE TABLE PRICE_LIST_ITEM (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LIST_ID     NUMBER NOT NULL,
    PRODUCT_ID  NUMBER NOT NULL,
    PRICE       NUMBER(14,2) NOT NULL,      -- without VAT, like the product sale price
    CONSTRAINT UQ_PRICE_LIST_ITEM UNIQUE (LIST_ID, PRODUCT_ID),
    CONSTRAINT FK_PLI_LIST FOREIGN KEY (LIST_ID) REFERENCES PRICE_LIST (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PLI_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID) ON DELETE CASCADE
);
ALTER TABLE CLIENT ADD (PRICE_LIST_ID NUMBER);
