-- V22: shops and warehouses (locations), optional module (off by default).
-- Stock is counted per location. Everything recorded before (location empty)
-- belongs to the main location, so nothing changes until locations are used.

ALTER TABLE APP_CONFIG ADD (MOD_LOCATIONS NUMBER(1) DEFAULT 0 NOT NULL);

CREATE TABLE LOCATION (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE        VARCHAR2(20)  NOT NULL,
    NAME        VARCHAR2(100) NOT NULL,
    KIND        VARCHAR2(10)  DEFAULT 'SHOP' NOT NULL,     -- SHOP or WAREHOUSE
    ADDRESS     VARCHAR2(300),
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    IS_MAIN     NUMBER(1) DEFAULT 0 NOT NULL,              -- holds everything recorded without a location
    CONSTRAINT UQ_LOCATION_CODE UNIQUE (CODE),
    CONSTRAINT CK_LOCATION_KIND CHECK (KIND IN ('SHOP', 'WAREHOUSE'))
);
INSERT INTO LOCATION (CODE, NAME, KIND, IS_MAIN) VALUES ('MAIN', 'Kryesore', 'SHOP', 1);

ALTER TABLE ORDER_LINE ADD (LOCATION_ID NUMBER);
ALTER TABLE STOCK_ADJUSTMENT ADD (LOCATION_ID NUMBER);
ALTER TABLE STOCK_COUNT ADD (LOCATION_ID NUMBER);
ALTER TABLE APP_USER ADD (LOCATION_ID NUMBER);           -- the user's own shop
CREATE INDEX IX_LINE_LOCATION ON ORDER_LINE (LOCATION_ID, PRODUCT_NAME);
CREATE INDEX IX_ADJ_LOCATION ON STOCK_ADJUSTMENT (LOCATION_ID, PRODUCT_NAME);

-- Transfers between locations: the header; its movements are stock adjustments with REF_NO = CODE.
CREATE SEQUENCE TRANSFER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE STOCK_TRANSFER (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE           VARCHAR2(20)  NOT NULL,
    FROM_LOCATION  NUMBER NOT NULL,
    TO_LOCATION    NUMBER NOT NULL,
    MOVED_ON       DATE   NOT NULL,
    NOTE           VARCHAR2(300),
    CREATED_BY     VARCHAR2(100) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_TRANSFER_CODE UNIQUE (CODE)
);
